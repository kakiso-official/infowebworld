/**
 * One-off taxonomy export.
 *
 * Reads the launched + navigable categories from cPanel MySQL once and writes
 * them as a typed static file at app/config/categories-data.ts. The runtime
 * then imports that file instead of fetching /api/categories on every Navbar
 * mount — that single change saves ~8.5 MB per fresh page load.
 *
 * Re-run this script whenever the admin adds, launches, renames, or deletes
 * a category. Commit the regenerated app/config/categories-data.ts + push.
 *
 * Run with:
 *   node scripts/export-categories.mjs
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { dirname } from 'node:path'
import mysql from 'mysql2/promise'

const env = {}
const raw = readFileSync('.env.local', 'utf8')
for (const line of raw.split(/\r?\n/)) {
  const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/)
  if (!m) continue
  let v = m[2]
  if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) v = v.slice(1, -1)
  env[m[1]] = v
}

const conn = await mysql.createConnection({
  host: env.DATABASE_HOST,
  port: Number(env.DATABASE_PORT || 3306),
  database: env.DATABASE_NAME,
  user: env.DATABASE_USER,
  password: env.DATABASE_PASSWORD,
  ssl: env.DATABASE_SSL === 'true' ? { rejectUnauthorized: false } : undefined,
})

console.log('Connected to', env.DATABASE_HOST)

/* Matches the same filter /api/categories used: launched + active + navigable.
   Columns are the minimum the Navbar + CategoriesBrowse actually read.
   The correlated COUNT subquery is the same listing_count we were computing
   live on every API hit — here it runs ONCE at export time.

   AI&ML v3 (2026-05) introduces L4 + L5 as navigable categories under the
   ai-ml L1 sector. We climb up to four parents (p → gp → ggp → gggp) so
   sector_slug resolves correctly for L1..L5. */
const [rows] = await conn.execute(`
  SELECT c.id, c.parent_id, c.level, c.name, c.slug, c.color, c.sort_order,
         p.name AS parent_name, p.slug AS parent_slug,
         CASE
           WHEN c.level = 1 THEN c.slug
           WHEN c.level = 2 THEN p.slug
           WHEN c.level = 3 THEN gp.slug
           WHEN c.level = 4 THEN ggp.slug
           WHEN c.level = 5 THEN gggp.slug
         END AS sector_slug,
         (SELECT COUNT(*) FROM submissions s
          WHERE s.category_id = c.id AND s.status IN ('active','paid')) AS listing_count
  FROM categories c
  LEFT JOIN categories p    ON p.id    = c.parent_id
  LEFT JOIN categories gp   ON gp.id   = p.parent_id
  LEFT JOIN categories ggp  ON ggp.id  = gp.parent_id
  LEFT JOIN categories gggp ON gggp.id = ggp.parent_id
  WHERE c.is_launched = 1 AND c.is_active = 1 AND c.is_navigation = 1
  ORDER BY c.sort_order, c.id
`)

const lvl = n => rows.filter(r => r.level === n).length
const l1 = lvl(1), l2 = lvl(2), l3 = lvl(3), l4 = lvl(4), l5 = lvl(5)
console.log(`Fetched ${rows.length} rows  (L1=${l1}  L2=${l2}  L3=${l3}  L4=${l4}  L5=${l5})`)

await conn.end()

/* Serialize each row inline as a compact object literal. Writing JSON.stringify
   on the whole array works too, but keeping one row per line makes git diffs
   readable when only a handful of categories change between exports. */
const now = new Date().toISOString()
const lines = rows.map(r => {
  const parts = [
    `id:${Number(r.id)}`,
    `parent_id:${r.parent_id == null ? 'null' : Number(r.parent_id)}`,
    `level:${Number(r.level)}`,
    `name:${JSON.stringify(String(r.name ?? ''))}`,
    `slug:${JSON.stringify(String(r.slug ?? ''))}`,
    `color:${JSON.stringify(String(r.color ?? '#E8553D'))}`,
    `sort_order:${Number(r.sort_order ?? 0)}`,
    `parent_name:${r.parent_name == null ? 'null' : JSON.stringify(String(r.parent_name))}`,
    `parent_slug:${r.parent_slug == null ? 'null' : JSON.stringify(String(r.parent_slug))}`,
    `sector_slug:${r.sector_slug == null ? 'null' : JSON.stringify(String(r.sector_slug))}`,
    `listing_count:${Number(r.listing_count ?? 0)}`,
  ]
  return `  { ${parts.join(', ')} },`
})

const out = `/**
 * AUTO-GENERATED by scripts/export-categories.mjs — do not hand-edit.
 *
 * Generated: ${now}
 * Source:    ${env.DATABASE_NAME}@${env.DATABASE_HOST}
 * Rows:      ${rows.length}  (L1=${l1}  L2=${l2}  L3=${l3}  L4=${l4}  L5=${l5})
 *
 * If admin adds/launches/renames a category, re-run:
 *     node scripts/export-categories.mjs
 * Then commit this file + push. Deploy picks up the new taxonomy.
 */

export type StaticCategoryRow = {
  id: number
  parent_id: number | null
  level: number
  name: string
  slug: string
  color: string
  sort_order: number
  parent_name: string | null
  parent_slug: string | null
  sector_slug: string | null
  listing_count: number
}

export const CATEGORIES_GENERATED_AT = ${JSON.stringify(now)}

export const CATEGORIES: StaticCategoryRow[] = [
${lines.join('\n')}
]
`

const outPath = 'app/config/categories-data.ts'
mkdirSync(dirname(outPath), { recursive: true })
writeFileSync(outPath, out, 'utf8')
const size = readFileSync(outPath).length
console.log(`Wrote ${outPath}  (${size.toLocaleString()} bytes, ${(size / 1024).toFixed(1)} KB)`)

/* ── Companion file: cross-sector category-name collisions ────────────
   A category name reused by two different sectors would otherwise emit a
   byte-identical <title> and meta description on both pages, and they
   would compete with each other in search. buildCategoryMeta() adds a
   sector qualifier for exactly the names in this set, so the set must be
   regenerated whenever the taxonomy changes — hence it lives here rather
   than being hand-maintained. */
const normName = (n) => String(n || '').toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim()
const sectorsByName = new Map()
const rowsByName = new Map()
for (const r of rows) {
  if (Number(r.level) < 2 || !r.sector_slug) continue
  const n = normName(r.name)
  if (!sectorsByName.has(n)) { sectorsByName.set(n, new Set()); rowsByName.set(n, []) }
  sectorsByName.get(n).add(r.sector_slug)
  rowsByName.get(n).push(r)
}
const collisions = [...sectorsByName.entries()].filter(([, s]) => s.size > 1).map(([n]) => n).sort()
const collisionRows = collisions.reduce((a, n) => a + rowsByName.get(n).length, 0)

const collisionOut = `/**
 * AUTO-GENERATED by scripts/export-categories.mjs — do not hand-edit.
 *
 * Category names that exist in MORE THAN ONE L1 sector. Two such pages
 * would otherwise emit a byte-identical <title> and meta description and
 * compete with each other in search — e.g. before this list,
 *   /it-services-agencies/game-development-services
 *   /software-saas/game-development
 * both titled "Top Game Development Companies (2026) - Reviews & Pricing".
 *
 * Names are normalised (lowercased, non-alphanumerics collapsed to single
 * spaces) so slug/punctuation variations still match.
 *
 * Collisions: ${collisions.length} names across ${collisionRows} category rows.
 * Derived from app/config/categories-data.ts (${rows.length} rows).
 */

export const CROSS_SECTOR_NAME_COLLISIONS: ReadonlySet<string> = new Set([
${collisions.map(n => {
  const rs = rowsByName.get(n)
  const sectors = [...new Set(rs.map(r => r.sector_slug))].join(', ')
  return `  '${n.replace(/'/g, "\\'")}',`.padEnd(48) + `// ${rs[0].name} — ${sectors}`
}).join('\n')}
])

/** Normalise a category name for collision lookup. */
export function normalizeCategoryName(name: string): string {
  return (name || '').toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim()
}

/** True when this name is reused by another sector and needs qualifying. */
export function isCrossSectorCollision(name: string): boolean {
  return CROSS_SECTOR_NAME_COLLISIONS.has(normalizeCategoryName(name))
}
`
const collisionPath = 'app/config/category-name-collisions.ts'
writeFileSync(collisionPath, collisionOut, 'utf8')
console.log(`Wrote ${collisionPath}  (${collisions.length} colliding names across ${collisionRows} rows)`)
