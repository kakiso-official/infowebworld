/**
 * One-off taxonomy export.
 *
 * Reads the launched + navigable categories from cPanel MySQL once and writes
 * them as a typed static file at app/config/categories-data.ts. The runtime
 * then imports that file instead of fetching /api/categories on every Navbar
 * mount — that single change saves ~8.5 MB per fresh page load.
 *
 * Re-run this script whenever the admin adds, launches, renames, or deletes
 * a category. Commit the regenerated app/config/categories-data.ts + push.
 *
 * Run with:
 *   node scripts/export-categories.mjs
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { dirname } from 'node:path'
import mysql from 'mysql2/promise'

const env = {}
const raw = readFileSync('.env.local', 'utf8')
for (const line of raw.split(/\r?\n/)) {
  const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/)
  if (!m) continue
  let v = m[2]
  if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) v = v.slice(1, -1)
  env[m[1]] = v
}

const conn = await mysql.createConnection({
  host: env.DATABASE_HOST,
  port: Number(env.DATABASE_PORT || 3306),
  database: env.DATABASE_NAME,
  user: env.DATABASE_USER,
  password: env.DATABASE_PASSWORD,
  ssl: env.DATABASE_SSL === 'true' ? { rejectUnauthorized: false } : undefined,
})

console.log('Connected to', env.DATABASE_HOST)

/* Matches the same filter /api/categories used: launched + active + navigable.
   Columns are the minimum the Navbar + CategoriesBrowse actually read.
   The correlated COUNT subquery is the same listing_count we were computing
   live on every API hit — here it runs ONCE at export time. */
const [rows] = await conn.execute(`
  SELECT c.id, c.parent_id, c.level, c.name, c.slug, c.color, c.sort_order,
         p.name AS parent_name, p.slug AS parent_slug,
         CASE
           WHEN c.level = 1 THEN c.slug
           WHEN c.level = 2 THEN p.slug
           WHEN c.level = 3 THEN gp.slug
         END AS sector_slug,
         (SELECT COUNT(*) FROM submissions s
          WHERE s.category_id = c.id AND s.status IN ('active','paid')) AS listing_count
  FROM categories c
  LEFT JOIN categories p  ON p.id = c.parent_id
  LEFT JOIN categories gp ON gp.id = p.parent_id
  WHERE c.is_launched = 1 AND c.is_active = 1 AND c.is_navigation = 1
  ORDER BY c.sort_order, c.id
`)

const l1 = rows.filter(r => r.level === 1).length
const l2 = rows.filter(r => r.level === 2).length
const l3 = rows.filter(r => r.level === 3).length
console.log(`Fetched ${rows.length} rows  (L1=${l1}  L2=${l2}  L3=${l3})`)

await conn.end()

/* Serialize each row inline as a compact object literal. Writing JSON.stringify
   on the whole array works too, but keeping one row per line makes git diffs
   readable when only a handful of categories change between exports. */
const now = new Date().toISOString()
const lines = rows.map(r => {
  const parts = [
    `id:${Number(r.id)}`,
    `parent_id:${r.parent_id == null ? 'null' : Number(r.parent_id)}`,
    `level:${Number(r.level)}`,
    `name:${JSON.stringify(String(r.name ?? ''))}`,
    `slug:${JSON.stringify(String(r.slug ?? ''))}`,
    `color:${JSON.stringify(String(r.color ?? '#E8553D'))}`,
    `sort_order:${Number(r.sort_order ?? 0)}`,
    `parent_name:${r.parent_name == null ? 'null' : JSON.stringify(String(r.parent_name))}`,
    `parent_slug:${r.parent_slug == null ? 'null' : JSON.stringify(String(r.parent_slug))}`,
    `sector_slug:${r.sector_slug == null ? 'null' : JSON.stringify(String(r.sector_slug))}`,
    `listing_count:${Number(r.listing_count ?? 0)}`,
  ]
  return `  { ${parts.join(', ')} },`
})

const out = `/**
 * AUTO-GENERATED by scripts/export-categories.mjs — do not hand-edit.
 *
 * Generated: ${now}
 * Source:    ${env.DATABASE_NAME}@${env.DATABASE_HOST}
 * Rows:      ${rows.length}  (L1=${l1}  L2=${l2}  L3=${l3})
 *
 * If admin adds/launches/renames a category, re-run:
 *     node scripts/export-categories.mjs
 * Then commit this file + push. Deploy picks up the new taxonomy.
 */

export type StaticCategoryRow = {
  id: number
  parent_id: number | null
  level: number
  name: string
  slug: string
  color: string
  sort_order: number
  parent_name: string | null
  parent_slug: string | null
  sector_slug: string | null
  listing_count: number
}

export const CATEGORIES_GENERATED_AT = ${JSON.stringify(now)}

export const CATEGORIES: StaticCategoryRow[] = [
${lines.join('\n')}
]
`

const outPath = 'app/config/categories-data.ts'
mkdirSync(dirname(outPath), { recursive: true })
writeFileSync(outPath, out, 'utf8')
const size = readFileSync(outPath).length
console.log(`Wrote ${outPath}  (${size.toLocaleString()} bytes, ${(size / 1024).toFixed(1)} KB)`)
