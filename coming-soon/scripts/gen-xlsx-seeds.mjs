/* ── 4. GO-LIVE (flip all 60 pending -> active) ──────────────────────────── */
function genGolive(all) {
  const sql = `-- ============================================================
-- GO-LIVE - xlsx-60 seed. Flips status 'pending' -> 'active' so the listings
-- render (/company/[slug] for products, /profile/[slug] for companies).
-- Run AFTER loading the 3 seed files AND reviewing in /iww-hq/submissions.
-- Then REDEPLOY (company /profile pages are SSG, built at deploy time).
-- Scoped to these exact slugs + unclaimed rows, so it can never touch a real
-- user's listing. They stay UNCLAIMED + FREE (payment 'unpaid', user_id NULL).
-- Re-runnable. Generated by scripts/gen-xlsx-seeds.mjs.
-- ============================================================

UPDATE submissions
   SET status = 'active', activated_at = NOW()
 WHERE user_id IS NULL
   AND status = 'pending'
   AND slug IN (${slugList(all)});

-- Verify (expect 60):
-- SELECT listing_mode, COUNT(*) FROM submissions
--  WHERE status='active' AND slug IN (${slugList(all)}) GROUP BY listing_mode;
`
  writeFileSync(D + 'golive-xlsx.sql', sql)
}

/* ── Targeted fix: rewrite ONLY key_features as objects (for rows already
   loaded from an earlier seed version that stored them as strings). ── */
function genKeyFeaturesFix(rows) {
  let sql = `-- ============================================================
-- FIX - populate key_features for the 10 xlsx AI/ML products.
-- The listing page reads key_features as [{name, description}] objects; the
-- first seed stored plain strings, so the "Key features" section rendered blank.
-- This rewrites them as objects. Run in phpMyAdmin AFTER seed-xlsx-aiml-products.sql.
-- Touches ONLY key_features (screenshots/status/everything else untouched). Re-runnable.
-- The regenerated seed already has this shape, so fresh loads don't need this.
-- ============================================================

`
  for (const r of rows) {
    const feats = r.key_features || r.features || []
    sql += `UPDATE submissions SET key_features = ${json(keyFeatureObjs(feats))} WHERE slug = '${r.slug}' AND listing_mode = 'product';\n`
  }
  writeFileSync(D + 'fix-xlsx-aiml-key-features.sql', sql)
}

const p = genProducts()
const c = genCompanies()
const l = genLocal()
genGolive([...p, ...c, ...l])
genKeyFeaturesFix(p)
console.log(`Generated: ${p.length} products, ${c.length} companies, ${l.length} local, go-live (${p.length + c.length + l.length} slugs), key-features fix.`)
