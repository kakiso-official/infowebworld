/**
 * Generate the xlsx-60 seed SQL from the validated research JSON.
 * Emits 4 files into database/:
 *   seed-xlsx-aiml-products.sql      (10 AI/ML, listing_mode='product', full enrichment)
 *   seed-xlsx-companies.sql          (40 SaaS/IT/Startups/ProServices, listing_mode='company')
 *   seed-xlsx-local-businesses.sql   (10, listing_mode='company' + lb_*, Yelp design)
 *   golive-xlsx.sql                  (flip all 60 pending -> active)
 *
 * All rows: status='pending', payment_status='unpaid', user_id=NULL (claimable).
 * Re-runnable (each seed DELETEs its own slugs first). Run by the user in phpMyAdmin.
 * Mirrors the proven seed-aiml-100 / enrich-aiml / seed-pro-services-200 / seed-local-businesses shapes.
 *   node scripts/gen-xlsx-seeds.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'

const R = 'scripts/research-xlsx/'
const D = 'database/'
const load = (f) => JSON.parse(readFileSync(R + f, 'utf8'))

/* ── SQL helpers ─────────────────────────────────────────────────────────── */
/* MySQL treats \ as an escape char inside '...': escape backslash first, then quote. */
const esc = (s) => String(s).replace(/\\/g, '\\\\').replace(/'/g, "''")
const q = (v) => (v == null || v === '') ? 'NULL' : "'" + esc(v) + "'"
const num = (v) => (v == null || v === '' || Number.isNaN(Number(v))) ? 'NULL' : String(Number(v))
const json = (v) => (v == null) ? 'NULL' : "'" + esc(JSON.stringify(v)) + "'"
const bit = (v) => (v ? 1 : 0)
const domainOf = (w) => (w || '').replace(/^https?:\/\//, '').replace(/^www\./, '').split('/')[0]
const logo = (w) => { const d = domainOf(w); return d ? `https://www.google.com/s2/favicons?domain=${d}&sz=256` : null }
const cat = (slug, fb) => `COALESCE((SELECT id FROM categories WHERE slug=${q(slug)} LIMIT 1), ${fb})`
const ctry = (code) => `COALESCE((SELECT id FROM countries WHERE code=${q(code || 'US')} LIMIT 1), @fallback_country)`
const slugList = (rows) => rows.map((r) => `'${r.slug}'`).join(', ')

/* key_features is read by the listing page as [{name, description}] objects
   (KeyFeature[]), NOT strings. Convert each real feature string -> object,
   splitting out a description ONLY from text already present (trailing
   parenthetical or "Name: detail") — never inventing new claims. */
function toKeyFeature(s) {
  s = String(s).trim()
  let m = s.match(/^(.+?)\s*\(([^()]+)\)\s*$/)            // "Name (detail)"
  if (!m) m = s.match(/^([^:]{3,48}):\s+(.+)$/)            // "Name: detail"
  if (m) {
    let desc = m[2].trim()
    desc = desc.charAt(0).toUpperCase() + desc.slice(1)
    if (!/[.!?]$/.test(desc)) desc += '.'
    return { name: m[1].trim(), description: desc }
  }
  return { name: s, description: '' }
}
const keyFeatureObjs = (arr) => (arr || []).map(toKeyFeature)

const HEAD = (title, body) => `-- ============================================================
-- ${title}
-- Generated by scripts/gen-xlsx-seeds.mjs - do not edit by hand.
-- Source: InfoWebWorld-Companies-by-Category.xlsx (60 companies).
-- All data real / web-verified. status='pending', user_id=NULL (claimable).
-- Re-runnable: deletes its own slugs first. Run in phpMyAdmin -> SQL.
-- ============================================================

SET @free_plan        := (SELECT id FROM plans WHERE is_active = 1 ORDER BY price ASC LIMIT 1);
SET @fallback_country := (SELECT id FROM countries WHERE code = 'US' LIMIT 1);
${body}`

/* ── 1. AI/ML PRODUCTS ───────────────────────────────────────────────────── */
function genProducts() {
  const rows = [...load('aiml-a.json'), ...load('aiml-b.json')]
  const cols = `uuid, company_name, slug, contact_name, email, phone_code, phone, website,
  category_id, country_id, city, state, hq_location, tagline, description, logo_url,
  founded_year, team_size, linkedin, twitter,
  listing_mode, is_hiring,
  header_tags, industries_served, use_cases, target_company_sizes,
  key_features, features, pricing_model, pricing_tiers, integrations,
  support_channels, training_options, languages, compliance, faqs, pros, cons,
  starting_price, starting_price_period, has_free_trial, has_free_version, has_ios_app, has_android_app,
  status, payment_status, plan_id, user_id, created_at, updated_at`

  let body = `SET @aiml_sector     := (SELECT id FROM categories WHERE slug = 'ai-ml' AND level = 1 LIMIT 1);

DELETE FROM submissions WHERE listing_mode = 'product' AND user_id IS NULL AND slug IN (${slugList(rows)});
`
  for (const r of rows) {
    const feats = r.key_features || r.features || []
    body += `
-- ${r.name} (${r.country_code} - ${r.category_slug})
INSERT INTO submissions (
  ${cols}
) SELECT
  UUID(), ${q(r.name)}, ${q(r.slug)}, ${q(r.name + ' Team')}, ${q(r.email || 'info@' + domainOf(r.website))},
  ${q(r.phone_code)}, ${q(r.phone)}, ${q(r.website)},
  ${cat(r.category_slug, '@aiml_sector')}, ${ctry(r.country_code)}, ${q(r.city)}, ${q(r.state)}, ${q(r.hq_location)},
  ${q(r.tagline)}, ${q(r.description)}, ${q(logo(r.website))},
  ${num(r.founded_year)}, ${q(r.team_size)}, ${q(r.linkedin)}, ${q(r.twitter)},
  'product', 0,
  ${json(r.header_tags)}, ${json(r.industries_served)}, ${json(r.use_cases)}, ${json(r.target_company_sizes)},
  ${json(keyFeatureObjs(feats))}, ${json(feats)}, ${q(r.pricing_model)}, ${json(r.pricing_tiers)}, ${json(r.integrations)},
  ${json(r.support_channels)}, ${json(r.training_options)}, ${json(r.languages)}, ${json(r.compliance || [])}, ${json(r.faqs)}, ${json(r.pros)}, ${json(r.cons)},
  ${num(r.starting_price)}, ${q(r.starting_price_period)}, ${bit(r.has_free_trial)}, ${bit(r.has_free_version)}, ${bit(r.has_ios_app)}, ${bit(r.has_android_app)},
  'pending', 'unpaid', @free_plan, NULL, NOW(), NOW();
`
  }
  writeFileSync(D + 'seed-xlsx-aiml-products.sql', HEAD('InfoWebWorld - xlsx AI/ML PRODUCT listings (10, full enrichment)', body))
  return rows
}

/* ── 2. COMPANIES (SaaS / IT / Startups / Pro Services) ──────────────────── */
const SECTOR_VAR = {
  saas: '@saas_sector', agency_it: '@it_sector', startup: '@startup_sector', agency_ps: '@ps_sector',
}
function genCompanies() {
  const groups = [
    ['saas.json', 'saas', '@saas_sector'],
    ['it-services.json', 'agency_it', '@it_sector'],
    ['startups.json', 'startup', '@startup_sector'],
    ['pro-services.json', 'agency_ps', '@ps_sector'],
  ]
  const rows = []
  for (const [f, kind, v] of groups) for (const r of load(f)) rows.push({ ...r, _kind: kind, _sectorVar: v })

  const cols = `uuid, company_name, slug, contact_name, email, phone_code, phone, website,
  category_id, country_id, city, state, hq_location, tagline, description, logo_url,
  founded_year, team_size, linkedin, twitter, facebook,
  listing_mode, is_hiring, header_tags, industries_served, languages, awards, faqs,
  min_project_size, hourly_rate, common_project_size, intro_video_url, timezones,
  service_lines, focus_breakdown, client_logos, clients_summary,
  status, payment_status, plan_id, user_id, created_at, updated_at`

  let body = `SET @saas_sector     := (SELECT id FROM categories WHERE slug = 'software-saas' AND level = 1 LIMIT 1);
SET @it_sector       := (SELECT id FROM categories WHERE slug = 'it-services-agencies' AND level = 1 LIMIT 1);
SET @startup_sector  := (SELECT id FROM categories WHERE slug = 'startups-innovation' AND level = 1 LIMIT 1);
SET @ps_sector       := (SELECT id FROM categories WHERE slug = 'professional-services' AND level = 1 LIMIT 1);

DELETE FROM submissions WHERE listing_mode = 'company' AND user_id IS NULL AND slug IN (${slugList(rows)});
`
  for (const r of rows) {
    body += `
-- ${r.name} (${r.country_code} - ${r.category_slug})
INSERT INTO submissions (
  ${cols}
) SELECT
  UUID(), ${q(r.name)}, ${q(r.slug)}, ${q(r.name + ' Team')}, ${q(r.email || 'info@' + domainOf(r.website))},
  ${q(r.phone_code)}, ${q(r.phone)}, ${q(r.website)},
  ${cat(r.category_slug, r._sectorVar)}, ${ctry(r.country_code)}, ${q(r.city)}, ${q(r.state)}, ${q(r.hq_location)},
  ${q(r.tagline)}, ${q(r.description)}, ${q(logo(r.website))},
  ${num(r.founded_year)}, ${q(r.team_size)}, ${q(r.linkedin)}, ${q(r.twitter)}, ${q(r.facebook)},
  'company', ${bit(r.is_hiring)}, ${json(r.header_tags)}, ${json(r.industries_served)}, ${json(r.languages)}, ${json(r.awards && r.awards.length ? r.awards : null)}, ${json(r.faqs)},
  ${q(r.min_project_size)}, ${q(r.hourly_rate)}, ${q(r.common_project_size)}, ${q(r.intro_video_url)}, ${json(r.timezones)},
  ${json(r.service_lines && r.service_lines.length ? r.service_lines : null)}, ${json(r.focus_breakdown && r.focus_breakdown.length ? r.focus_breakdown : null)}, ${json(r.client_logos && r.client_logos.length ? r.client_logos : null)}, ${q(r.clients_summary)},
  'pending', 'unpaid', @free_plan, NULL, NOW(), NOW();
`
  }
  writeFileSync(D + 'seed-xlsx-companies.sql', HEAD('InfoWebWorld - xlsx COMPANY listings (40: SaaS/IT/Startups/Pro Services)', body))
  return rows
}

